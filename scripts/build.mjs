/**
 * Build the browser half of the plugin.
 *
 * Concatenates the plain-JS source modules into the single `client.js` module
 * the Harness Client ModuleLoader expects. Each source file shares the factory
 * scope (`React`, `h`, `APP`) and must not use import/export.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const modules = [
  'src/locale-zh.js',
  'src/locale-en.js',
  'src/engine.js',
  'src/charts.js',
  'src/styles.js',
  'src/views.js',
];

const body = modules
  .map((file) => `  /* ---- ${file} ---- */\n${readFileSync(join(root, file), 'utf8').trimEnd()}`)
  .join('\n\n');

const output = `/**
 * ${pkg.name} — browser half.
 * Generated by scripts/build.mjs from src/*; edit src/ and rebuild, never this file.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const React = require('react');
    const h = React.createElement;
    const APP = {};

${body}

    return APP.plugin;
  },
});
`;

writeFileSync(join(root, 'client.js'), output, 'utf8');
console.log(`client.js written (${output.length} bytes)`);
